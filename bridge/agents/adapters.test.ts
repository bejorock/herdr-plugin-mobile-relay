import { afterEach, describe, expect, test } from "bun:test";
import { mkdtemp, mkdir, readFile, rm, writeFile, readdir } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { claudeDecision, claudeRequest } from "../../adapters/claude-interactions.ts";
import { manageIntegrations } from "../../scripts/agent-integrations.ts";
const dirs: string[] = [];
afterEach(async () => { await Promise.all(dirs.splice(0).map((dir) => rm(dir, { force: true, recursive: true }))); });
describe("native adapter output fixtures (not native Claude execution)", () => {
  const input = { hook_event_name: "PreToolUse", tool_name: "AskUserQuestion", tool_use_id: "tool-123", agent_id: "child-a", tool_input: { questions: [{ question: "Choose?", header: "Choice", options: [{ label: "a" }, { label: "b" }] }, { question: "Colors?", header: "Colors", multiSelect: true, options: [{ label: "red" }, { label: "blue" }] }] } };
  test("question event preserves correlation and native answer schema", () => {
    expect(claudeRequest(input)).toMatchObject({ interactionKind: "elicitation", toolCallId: "tool-123", executionId: "child-a", schema: { required: ["q1", "q2"] } });
    expect(claudeDecision(input, { action: "accept", content: { q1: "a", q2: ["blue", "red"] } })).toEqual({ hookSpecificOutput: { hookEventName: "PreToolUse", permissionDecision: "allow", updatedInput: { ...input.tool_input, answers: { "Choose?": "a", "Colors?": "red,blue" } } } });
    expect(claudeDecision(input, { action: "accept", content: { q1: "invented", q2: ["red"] } })).toBeNull();
    expect(claudeDecision(input, { action: "cancel" })).toBeNull();
  });
  test("permissions return native decisions; plan rejection denies instead of falling through", () => {
    const permission = { hook_event_name: "PermissionRequest", tool_name: "Bash", tool_input: { command: "echo hello" } };
    expect(claudeDecision(permission, { optionId: "allow_once" })).toEqual({ hookSpecificOutput: { hookEventName: "PermissionRequest", decision: { behavior: "allow" } } });
    expect(claudeDecision(permission, { optionId: "reject_once" })).toMatchObject({ hookSpecificOutput: { decision: { behavior: "deny" } } });
    expect(claudeDecision({ ...permission, hook_event_name: "PreToolUse", tool_name: "ExitPlanMode" }, { optionId: "reject_once" })).toMatchObject({ hookSpecificOutput: { permissionDecision: "deny" } });
    expect(claudeDecision(permission, { outcome: "cancelled" })).toBeNull();
  });
  test("unsupported tools/malformed questions do not become remote permissions", () => {
    expect(claudeRequest({ ...input, tool_name: "Read" })).toBeNull();
    expect(claudeRequest({ ...input, tool_input: { questions: [{ question: "Choose?", header: "x", options: [{ label: "a" }, { label: "a" }] }] } })).toBeNull();
  });
});
describe("explicit integration settings management", () => {
  test("migrates only relay-owned entries, preserves Herdr/unrelated hooks, backs up and uninstalls", async () => {
    const home = await mkdtemp(join(tmpdir(), "relay-install-")); dirs.push(home);
    const pi = join(home, ".pi", "agent"), claude = join(home, ".claude");
    await mkdir(join(pi, "extensions"), { recursive: true }); await mkdir(claude, { recursive: true });
    await writeFile(join(pi, "extensions", "herdr-relay-acp.ts"), "// Generated by Herdr Mobile Relay hooks-install.\n");
    await writeFile(join(pi, "settings.json"), JSON.stringify({ extensions: ["+extensions/herdr-relay-acp.ts", "+extensions/herdr-agent-state.ts", "other.ts"], unrelated: true }));
    const old = `sh '${join(claude, "hooks", "herdr-relay-acp.sh")}'`;
    const native = { type: "command", command: "bash herdr-agent-state.sh" };
    await writeFile(join(claude, "settings.json"), JSON.stringify({ hooks: { PreToolUse: [{ matcher: "*", hooks: [{ type: "command", command: old }, native] }], Stop: [{ hooks: [{ type: "command", command: "other.sh" }] }] }, unrelated: true }));
    await manageIntegrations("install", { home, stateDir: join(home, "private state") });
    const settings = JSON.parse(await readFile(join(pi, "settings.json"), "utf8"));
    expect(settings.extensions).toEqual(["+extensions/herdr-agent-state.ts", "other.ts", "+extensions/herdr-relay-interactions.ts"]);
    expect((await readdir(pi)).some((name) => name.startsWith("settings.json.relay-backup"))).toBe(true);
    expect((await readdir(join(pi, "extensions")))).not.toContain("herdr-relay-acp.ts");
    const c = JSON.parse(await readFile(join(claude, "settings.json"), "utf8"));
    expect(c.hooks.PreToolUse[0].hooks).toEqual([native]); expect(c.hooks.Stop).toHaveLength(1); expect(c.unrelated).toBe(true);
    expect(await manageIntegrations("status", { home })).toEqual({ pi: true, claude: true });
    await manageIntegrations("install", { home, stateDir: join(home, "private state") });
    expect((await readdir(join(pi, "extensions")))).not.toContain("herdr-relay-acp.ts");
    await manageIntegrations("uninstall", { home });
    expect(await manageIntegrations("status", { home })).toEqual({ pi: false, claude: false });
    expect((await readdir(join(pi, "extensions")))).not.toContain("herdr-relay-interactions.ts");
  });
});
