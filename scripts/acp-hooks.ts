#!/usr/bin/env bun
/**
 * Installs only this relay's Pi extension. It intentionally never runs as part of `start`: modifying
 * an agent's user configuration is an explicit operator action. The extension is self-contained so
 * it does not depend on this checkout surviving plugin updates, and sends only best-effort local
 * events to the owner-only relay hook socket.
 */
import { chmod, mkdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import { dirname, join } from "node:path";

const PI_MARKER = "+extensions/herdr-relay-acp.ts";
const piExtensionPath = join(homedir(), ".pi", "agent", "extensions", "herdr-relay-acp.ts");
const piSettingsPath = join(homedir(), ".pi", "agent", "settings.json");
const CLAUDE_MARKER = "herdr-relay-acp claude-hook";
const claudeHookPath = join(homedir(), ".claude", "hooks", "herdr-relay-acp.sh");
const claudeSettingsPath = join(homedir(), ".claude", "settings.json");
const socketPath = process.env.HERDR_PLUGIN_STATE_DIR
  ? join(process.env.HERDR_PLUGIN_STATE_DIR, "agent-hook.sock")
  : join(homedir(), ".local", "state", "rad-herdr-mobile-relay", "agent-hook.sock");

type Settings = { extensions?: unknown; [key: string]: unknown };

function usage(): never {
  console.error("usage: acp-hooks.ts {install|status|uninstall} [pi|claude]");
  process.exit(2);
}

async function readSettings(path: string): Promise<Settings> {
  try {
    const value: unknown = JSON.parse(await readFile(path, "utf8"));
    if (typeof value !== "object" || value === null || Array.isArray(value)) throw new Error("settings root must be an object");
    if (value.extensions !== undefined && !Array.isArray(value.extensions)) throw new Error("settings extensions must be an array");
    return value as Settings;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return {};
    throw error;
  }
}

async function writeSettings(path: string, settings: Settings): Promise<void> {
  await mkdir(dirname(path), { recursive: true, mode: 0o700 });
  const temp = `${path}.${process.pid}.tmp`;
  await writeFile(temp, `${JSON.stringify(settings, null, 2)}\n`, { mode: 0o600 });
  await chmod(temp, 0o600);
  await rename(temp, path);
  await chmod(path, 0o600);
}

function extensionSource(path: string): string {
  return `// Generated by Herdr Mobile Relay hooks-install. Do not edit; rerun hooks-install to refresh.
import { createConnection } from "node:net";
const socketPath = ${JSON.stringify(path)};
// Must match Herdr's authoritative native Pi session binding exactly; the adapter name below
// still identifies this relay-owned hook separately from Herdr's integration extension.
const source = "herdr:pi";

export default function relayHook(pi) {
  let binding;
  let socket;
  let buffer = "";
  let sequence = 0;
  let reconnect;
  let ready = false;
  let pending = [];
  let streamMessageId = "";

  function disconnect() {
    if (reconnect) clearTimeout(reconnect);
    reconnect = undefined;
    if (socket) { try { socket.destroy(); } catch {} }
    socket = undefined;
    ready = false;
  }
  function connect() {
    if (!binding || socket) return;
    try {
      socket = createConnection({ path: socketPath });
      socket.setNoDelay(true);
      socket.on("connect", () => {
        try { socket.write(JSON.stringify({ version: 1, type: "hello", adapter: { kind: "pi", name: "herdr-relay", version: "1" }, binding }) + "\\n"); } catch {}
      });
      socket.on("data", (chunk) => {
        buffer += String(chunk);
        let newline = buffer.indexOf("\\n");
        while (newline >= 0) {
          const line = buffer.slice(0, newline); buffer = buffer.slice(newline + 1); newline = buffer.indexOf("\\n");
          try {
            const message = JSON.parse(line);
            if (message?.type === "hello_ack") { ready = true; flush(); }
            if (message?.type === "command" && message.command?.kind === "interaction.resolve") {
              pi.events.emit("herdr-relay:interaction-result", { requestId: message.command.interactionId, outcome: message.command.outcome });
            }
          } catch {}
        }
      });
      socket.on("error", () => {});
      socket.on("close", () => { socket = undefined; ready = false; if (binding) reconnect = setTimeout(connect, 1000); });
    } catch { socket = undefined; }
  }
  function write(value) {
    if (!socket || socket.destroyed || !ready) { connect(); return false; }
    try { socket.write(JSON.stringify(value) + "\\n"); return true; } catch { return false; }
  }
  function flush() {
    while (pending.length && write(pending[0])) pending.shift();
  }
  function event(eventId, payload) {
    if (!binding) return false;
    sequence += 1;
    const value = { version: 1, type: "event", eventId: eventId + ":" + sequence, sequence, event: payload };
    if (write(value)) return true;
    // A hook can emit immediately at session start, before the authenticated hello round trip.
    // Preserve its bounded order instead of losing the local interaction.
    if (pending.length < 64) pending.push(value);
    return true;
  }
  function session(ctx) {
    try {
      const value = ctx?.sessionManager?.getSessionFile?.();
      const paneId = process.env.HERDR_PANE_ID;
      const herdrSession = process.env.HERDR_SESSION || "default";
      if (typeof value !== "string" || !value || process.env.HERDR_ENV !== "1" || !paneId) return;
      binding = { herdrSession, paneId, agent: "pi", nativeSession: { source, agent: "pi", kind: "path", value } };
      disconnect(); connect();
    } catch {}
  }
  function tool(value, status) {
    if (!value?.toolCallId || !value?.toolName) return;
    event("tool:" + value.toolCallId, { kind: "tool.update", toolCallId: String(value.toolCallId), toolName: String(value.toolName), status, title: String(value.toolName), ...(value.isError ? { error: "Tool failed" } : {}) });
  }
  function messageStart(value) {
    if (value?.message?.role === "assistant") streamMessageId = "stream:" + (++sequence);
  }
  function messageDelta(value) {
    const update = value?.assistantMessageEvent;
    if (!streamMessageId || !update || typeof update.delta !== "string" || !update.delta) return;
    if (update.type === "text_delta") event("message:" + streamMessageId, { kind: "message.delta", messageId: streamMessageId, channel: "assistant", delta: update.delta });
    if (update.type === "thinking_delta") event("thought:" + streamMessageId, { kind: "message.delta", messageId: streamMessageId, channel: "thought", delta: update.delta });
  }
  // Public inter-extension bridge. Developers emit these events from another Pi extension; this
  // bridge owns socket framing, session binding, ACP delivery, and result fan-in.
  pi.events.on("herdr-relay:publish", (value) => {
    if (!value || typeof value !== "object") return;
    event("publish", { kind: "custom.notification", namespace: value.namespace, name: value.name, payload: value.payload });
  });
  pi.events.on("herdr-relay:request-permission", (value) => {
    if (!value || typeof value !== "object" || !value.requestId) return;
    event("permission:" + value.requestId, { kind: "interaction.request", interactionId: String(value.requestId), interactionKind: "permission", title: value.title, description: value.description, options: value.options });
  });
  pi.events.on("herdr-relay:request-elicitation", (value) => {
    if (!value || typeof value !== "object" || !value.requestId) return;
    event("elicitation:" + value.requestId, { kind: "interaction.request", interactionId: String(value.requestId), interactionKind: "elicitation", title: value.title, description: value.description, options: value.options, schema: value.schema });
  });
  pi.on("session_start", (_event, ctx) => session(ctx));
  pi.on("input", (_event, ctx) => session(ctx));
  pi.on("agent_start", (_event, ctx) => { session(ctx); event("state", { kind: "agent.state", state: "running" }); });
  pi.on("message_start", (value) => messageStart(value));
  pi.on("message_update", (value) => messageDelta(value));
  pi.on("tool_execution_start", (value) => tool(value, "in_progress"));
  pi.on("tool_execution_end", (value) => tool(value, value.isError ? "failed" : "completed"));
  pi.on("agent_settled", (_event, ctx) => { session(ctx); event("state", { kind: "agent.state", state: "idle" }); });
  pi.on("session_shutdown", () => disconnect());
}
`;
}

function claudeHookSource(path: string): string {
  return `#!/bin/sh
# Generated by Herdr Mobile Relay hooks-install. ${CLAUDE_MARKER}
# PermissionRequest and AskUserQuestion have different documented Claude hook output contracts.
# Any malformed/expired remote result deliberately produces no output, preserving Claude's local UI.
set -eu
[ "\${HERDR_ENV:-}" = "1" ] || exit 0
[ -n "\${HERDR_PANE_ID:-}" ] || exit 0
input="$(cat 2>/dev/null || true)"
python3 - "${path}" "\${HERDR_SESSION:-default}" "\${HERDR_PANE_ID}" "$input" <<'PY'
import json, secrets, socket, sys
sock_path, herdr_session, pane_id, raw = sys.argv[1:]
try: data = json.loads(raw) if raw.strip() else {}
except Exception: data = {}

def text(value, limit, required=True):
  return isinstance(value, str) and len(value) <= limit and (bool(value) if required else True)

def questions_from(value):
  if not isinstance(value, list) or not 1 <= len(value) <= 4: return None
  if len(json.dumps(value, separators=(",", ":"))) > 32768: return None
  parsed, used_questions = [], set()
  for index, question in enumerate(value, 1):
    if not isinstance(question, dict): return None
    prompt, header, options = question.get("question"), question.get("header"), question.get("options")
    multi = question.get("multiSelect", False)
    if not text(prompt, 1024) or prompt in used_questions or not text(header, 128) or type(multi) is not bool: return None
    if not isinstance(options, list) or not 1 <= len(options) <= 32: return None
    labels, choices = [], []
    for option in options:
      if not isinstance(option, dict) or not text(option.get("label"), 128) or option["label"] in labels: return None
      if multi and "," in option["label"]: return None
      description = option.get("description")
      if description is not None and not text(description, 512, False): return None
      labels.append(option["label"])
      choices.append({"const": option["label"], "title": option["label"], **({"description": description} if description else {})})
    field = {"title": header, "description": prompt}
    if multi:
      field.update({"type": "array", "items": {"type": "string", "oneOf": choices}, "minItems": 1, "maxItems": len(labels)})
    else: field.update({"type": "string", "oneOf": choices})
    parsed.append({"key": "q" + str(index), "question": question, "text": prompt, "labels": labels, "multi": multi, "schema": field})
    used_questions.add(prompt)
  return parsed

session_id, transcript = data.get("session_id"), data.get("transcript_path")
if not text(session_id, 256) or not text(transcript, 4096): raise SystemExit(0)
event_name, tool, tool_input = data.get("hook_event_name"), data.get("tool_name"), data.get("tool_input")
# Observability hooks never return a Claude decision. They use the same authenticated binding as
# interactions, but publish one bounded semantic event and exit immediately after acknowledgement.
observe = None
if event_name == "MessageDisplay" and text(data.get("message_id"), 256) and isinstance(data.get("delta"), str) and data["delta"]:
  observe = {"kind":"message.delta","messageId":"claude:" + data["message_id"],"channel":"assistant","delta":data["delta"][:65536]}
elif event_name == "Stop":
  observe = {"kind":"agent.state","state":"idle"}
elif event_name in ("PreToolUse", "PostToolUse", "PostToolUseFailure") and isinstance(tool, str) and isinstance(tool_input, dict) and not (event_name == "PreToolUse" and tool in ("AskUserQuestion", "ExitPlanMode")):
  tool_id = data.get("tool_use_id")
  if text(tool_id, 256):
    observe = {"kind":"tool.update","toolCallId":"claude:" + tool_id,"toolName":tool,"status":"in_progress" if event_name == "PreToolUse" else "failed" if event_name == "PostToolUseFailure" else "completed","title":tool}
if observe is None and (not isinstance(tool, str) or not isinstance(tool_input, dict)):
  raise SystemExit(0)
permission = event_name == "PermissionRequest"
questions = questions_from(tool_input.get("questions")) if event_name == "PreToolUse" and tool == "AskUserQuestion" else None
plan = tool_input.get("plan") if event_name == "PreToolUse" and tool == "ExitPlanMode" else None
if plan is not None and not text(plan, 48000): raise SystemExit(0)
if observe is None and not permission and questions is None and plan is None: raise SystemExit(0)
hello = {"version":1,"type":"hello","adapter":{"kind":"claude","name":"herdr-relay","version":"1"},"binding":{"herdrSession":herdr_session,"paneId":pane_id,"agent":"claude","nativeSession":{"source":"herdr:claude","agent":"claude","kind":"id","value":session_id},"transcriptPath":transcript}}
try:
  c=socket.socket(socket.AF_UNIX,socket.SOCK_STREAM); c.settimeout(240); c.connect(sock_path); c.sendall((json.dumps(hello)+"\\n").encode())
  buf=b""
  def line():
    global buf
    while b"\\n" not in buf: buf += c.recv(65536)
    out, buf = buf.split(b"\\n",1); return json.loads(out)
  line() # hello_ack
  iid = "claude:" + secrets.token_hex(16)
  if observe is not None:
    event = {"version":1,"type":"event","eventId":iid,"sequence":1,"event":observe}
    c.sendall((json.dumps(event)+"\\n").encode())
    line() # event_ack
    raise SystemExit(0)
  if permission:
    event = {"version":1,"type":"event","eventId":iid,"sequence":1,"event":{"kind":"interaction.request","interactionId":iid,"interactionKind":"permission","title":"Claude requests permission: " + tool,"description":json.dumps(tool_input, separators=(",",":"))[:2048],"options":[{"optionId":"allow_once","name":"Allow once"},{"optionId":"reject_once","name":"Deny"}]}}
  elif questions is not None:
    schema = {"properties": {item["key"]: item["schema"] for item in questions}, "required": [item["key"] for item in questions]}
    event = {"version":1,"type":"event","eventId":iid,"sequence":1,"event":{"kind":"interaction.request","interactionId":iid,"interactionKind":"elicitation","title":"Claude needs your input","description":"Answer Claude's questions to continue.","schema":schema,"timeoutMs":225000}}
  else:
    event = {"version":1,"type":"event","eventId":iid,"sequence":1,"event":{"kind":"interaction.request","interactionId":iid,"interactionKind":"permission","title":"Approve Claude's plan","description":"Approve the displayed plan to leave plan mode.","options":[{"optionId":"allow_once","name":"Approve plan"},{"optionId":"reject_once","name":"Keep planning"}],"timeoutMs":225000,"plan":{"planId":"claude:" + iid,"content":plan}}}
  c.sendall((json.dumps(event)+"\\n").encode())
  while True:
    message = line()
    command = message.get("command", {}) if isinstance(message, dict) else {}
    if command.get("kind") != "interaction.resolve" or command.get("interactionId") != iid: continue
    outcome = command.get("outcome", {})
    if permission or plan is not None:
      selected = outcome.get("outcome", {}).get("optionId") if isinstance(outcome, dict) else None
      if permission and selected == "allow_once":
        print(json.dumps({"hookSpecificOutput":{"hookEventName":"PermissionRequest","decision":{"behavior":"allow","updatedInput":tool_input}}}))
      elif permission and selected == "reject_once":
        print(json.dumps({"hookSpecificOutput":{"hookEventName":"PermissionRequest","decision":{"behavior":"deny","message":"Remote user declined"}}}))
      elif plan is not None and selected == "allow_once":
        print(json.dumps({"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"allow","updatedInput":tool_input}}))
      break
    content = outcome.get("content") if isinstance(outcome, dict) and outcome.get("action") == "accept" else None
    if not isinstance(content, dict) or set(content) != {item["key"] for item in questions}: break
    answers = {}
    for item in questions:
      answer = content[item["key"]]
      if item["multi"]:
        if not isinstance(answer, list) or not answer or len(answer) != len(set(answer)) or not all(isinstance(value, str) and value in item["labels"] for value in answer): break
        answers[item["text"]] = ",".join(value for value in item["labels"] if value in answer)
      elif not isinstance(answer, str) or answer not in item["labels"]: break
      else: answers[item["text"]] = answer
    else:
      print(json.dumps({"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"allow","updatedInput":{"questions":[item["question"] for item in questions],"answers":answers}}}))
    break
except Exception: pass
PY
`;
}

type ClaudeHookEvent = "SessionStart" | "PermissionRequest" | "PreToolUse" | "PostToolUse" | "PostToolUseFailure" | "MessageDisplay" | "Stop";

function claudeEntry(event: ClaudeHookEvent): Record<string, unknown> {
  return {
    ...(event === "SessionStart" ? { matcher: "^(startup|resume|clear|compact|fork)$" } : {}),
    hooks: [{ type: "command", command: `sh '${claudeHookPath}'`, timeout: event === "SessionStart" || event === "MessageDisplay" ? 10 : event === "Stop" ? 15 : 240 }],
  };
}

function isRelayClaudeEntry(value: unknown): boolean {
  if (!value || typeof value !== "object") return false;
  return JSON.stringify(value).includes(CLAUDE_MARKER) || JSON.stringify(value).includes(claudeHookPath);
}

async function installPi(): Promise<void> {
  const settings = await readSettings(piSettingsPath);
  const extensions = Array.isArray(settings.extensions) ? [...settings.extensions] : [];
  if (!extensions.includes(PI_MARKER)) extensions.push(PI_MARKER);
  settings.extensions = extensions;
  await mkdir(dirname(piExtensionPath), { recursive: true, mode: 0o700 });
  const temp = `${piExtensionPath}.${process.pid}.tmp`;
  await writeFile(temp, extensionSource(socketPath), { mode: 0o600 });
  await chmod(temp, 0o600);
  await rename(temp, piExtensionPath);
  await chmod(piExtensionPath, 0o600);
  await writeSettings(piSettingsPath, settings);
  console.log(`installed Pi ACP relay hook: ${piExtensionPath}`);
  console.log("restart Pi sessions to load the extension");
}

async function installClaude(): Promise<void> {
  const settings = await readSettings(claudeSettingsPath);
  const hooks = typeof settings.hooks === "object" && settings.hooks !== null && !Array.isArray(settings.hooks)
    ? { ...(settings.hooks as Record<string, unknown>) }
    : {};
  const starts = Array.isArray(hooks.SessionStart) ? [...hooks.SessionStart] : [];
  const permissions = Array.isArray(hooks.PermissionRequest) ? [...hooks.PermissionRequest] : [];
  const preToolUse = Array.isArray(hooks.PreToolUse) ? [...hooks.PreToolUse] : [];
  const postToolUse = Array.isArray(hooks.PostToolUse) ? [...hooks.PostToolUse] : [];
  const postToolUseFailure = Array.isArray(hooks.PostToolUseFailure) ? [...hooks.PostToolUseFailure] : [];
  const messageDisplay = Array.isArray(hooks.MessageDisplay) ? [...hooks.MessageDisplay] : [];
  const stops = Array.isArray(hooks.Stop) ? [...hooks.Stop] : [];
  if (!starts.some(isRelayClaudeEntry)) starts.push(claudeEntry("SessionStart"));
  if (!permissions.some(isRelayClaudeEntry)) permissions.push(claudeEntry("PermissionRequest"));
  if (!preToolUse.some(isRelayClaudeEntry)) preToolUse.push(claudeEntry("PreToolUse"));
  if (!postToolUse.some(isRelayClaudeEntry)) postToolUse.push(claudeEntry("PostToolUse"));
  if (!postToolUseFailure.some(isRelayClaudeEntry)) postToolUseFailure.push(claudeEntry("PostToolUseFailure"));
  if (!messageDisplay.some(isRelayClaudeEntry)) messageDisplay.push(claudeEntry("MessageDisplay"));
  if (!stops.some(isRelayClaudeEntry)) stops.push(claudeEntry("Stop"));
  hooks.SessionStart = starts;
  hooks.PermissionRequest = permissions;
  hooks.PreToolUse = preToolUse;
  hooks.PostToolUse = postToolUse;
  hooks.PostToolUseFailure = postToolUseFailure;
  hooks.MessageDisplay = messageDisplay;
  hooks.Stop = stops;
  settings.hooks = hooks;
  await mkdir(dirname(claudeHookPath), { recursive: true, mode: 0o700 });
  const temp = `${claudeHookPath}.${process.pid}.tmp`;
  await writeFile(temp, claudeHookSource(socketPath), { mode: 0o700 });
  await chmod(temp, 0o700);
  await rename(temp, claudeHookPath);
  await chmod(claudeHookPath, 0o700);
  await writeSettings(claudeSettingsPath, settings);
  console.log(`installed Claude ACP relay hook: ${claudeHookPath}`);
  console.log("restart Claude Code sessions to load the hook");
}

async function status(target: string): Promise<void> {
  if (target === "pi" || target === "all") {
    const settings = await readSettings(piSettingsPath);
    const enabled = Array.isArray(settings.extensions) && settings.extensions.includes(PI_MARKER);
    const installed = await Bun.file(piExtensionPath).exists();
    console.log(`pi extension: ${installed && enabled ? "installed" : installed ? "not enabled" : enabled ? "missing file" : "not installed"}`);
  }
  if (target === "claude" || target === "all") {
    const settings = await readSettings(claudeSettingsPath);
    const hooks = typeof settings.hooks === "object" && settings.hooks !== null ? settings.hooks as Record<string, unknown> : {};
    const starts = Array.isArray(hooks.SessionStart) ? hooks.SessionStart : [];
    const permissions = Array.isArray(hooks.PermissionRequest) ? hooks.PermissionRequest : [];
    const questions = Array.isArray(hooks.PreToolUse) ? hooks.PreToolUse : [];
    const post = Array.isArray(hooks.PostToolUse) ? hooks.PostToolUse : [];
    const postFailure = Array.isArray(hooks.PostToolUseFailure) ? hooks.PostToolUseFailure : [];
    const display = Array.isArray(hooks.MessageDisplay) ? hooks.MessageDisplay : [];
    const stops = Array.isArray(hooks.Stop) ? hooks.Stop : [];
    const enabled = starts.some(isRelayClaudeEntry) && permissions.some(isRelayClaudeEntry) && questions.some(isRelayClaudeEntry) && post.some(isRelayClaudeEntry) && postFailure.some(isRelayClaudeEntry) && display.some(isRelayClaudeEntry) && stops.some(isRelayClaudeEntry);
    const installed = await Bun.file(claudeHookPath).exists();
    console.log(`claude hook: ${installed && enabled ? "installed" : installed ? "not enabled" : enabled ? "missing file" : "not installed"}`);
  }
  console.log(`hook socket: ${socketPath}`);
}

async function uninstallPi(): Promise<void> {
  const settings = await readSettings(piSettingsPath);
  if (Array.isArray(settings.extensions)) {
    settings.extensions = settings.extensions.filter((entry) => entry !== PI_MARKER);
    await writeSettings(piSettingsPath, settings);
  }
  await rm(piExtensionPath, { force: true });
  console.log("removed Pi ACP relay hook; restart Pi sessions to unload it");
}

async function uninstallClaude(): Promise<void> {
  const settings = await readSettings(claudeSettingsPath);
  if (typeof settings.hooks === "object" && settings.hooks !== null && !Array.isArray(settings.hooks)) {
    const hooks = { ...(settings.hooks as Record<string, unknown>) };
    if (Array.isArray(hooks.SessionStart)) hooks.SessionStart = hooks.SessionStart.filter((entry) => !isRelayClaudeEntry(entry));
    if (Array.isArray(hooks.PermissionRequest)) hooks.PermissionRequest = hooks.PermissionRequest.filter((entry) => !isRelayClaudeEntry(entry));
    if (Array.isArray(hooks.PreToolUse)) hooks.PreToolUse = hooks.PreToolUse.filter((entry) => !isRelayClaudeEntry(entry));
    if (Array.isArray(hooks.PostToolUse)) hooks.PostToolUse = hooks.PostToolUse.filter((entry) => !isRelayClaudeEntry(entry));
    if (Array.isArray(hooks.PostToolUseFailure)) hooks.PostToolUseFailure = hooks.PostToolUseFailure.filter((entry) => !isRelayClaudeEntry(entry));
    if (Array.isArray(hooks.MessageDisplay)) hooks.MessageDisplay = hooks.MessageDisplay.filter((entry) => !isRelayClaudeEntry(entry));
    if (Array.isArray(hooks.Stop)) hooks.Stop = hooks.Stop.filter((entry) => !isRelayClaudeEntry(entry));
    settings.hooks = hooks;
    await writeSettings(claudeSettingsPath, settings);
  }
  await rm(claudeHookPath, { force: true });
  console.log("removed Claude ACP relay hook; restart Claude Code sessions to unload it");
}

const command = process.argv[2];
const target = process.argv[3] ?? (command === "status" ? "all" : "pi");
if (!["pi", "claude", "all"].includes(target)) usage();
if (command === "install") {
  if (target === "pi" || target === "all") await installPi();
  if (target === "claude" || target === "all") await installClaude();
} else if (command === "status") {
  await status(target);
} else if (command === "uninstall") {
  if (target === "pi" || target === "all") await uninstallPi();
  if (target === "claude" || target === "all") await uninstallClaude();
} else usage();
